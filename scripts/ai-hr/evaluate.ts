// Runs the scenario evaluation and writes docs/ai-hr-assistant/SCENARIO_REPORT.md and scenario-results.json.
// Run: pnpm tsx scripts/ai-hr/evaluate.ts [--quiet]
import { writeFileSync, mkdirSync } from "node:fs";
import { evaluateAll } from "../../src/staff/hrms/ai-hr/evaluate";
import { CATEGORIES, LIBRARY_VERSION, scenarios, validateLibrary } from "../../src/staff/hrms/ai-hr/scenarios";

const list = scenarios();
const v = validateLibrary(list);
const r = evaluateAll(list, LIBRARY_VERSION);
const pct = (a: number, b: number) => (b ? `${((a / b) * 100).toFixed(1)}%` : "n/a");
mkdirSync("docs/ai-hr-assistant", { recursive: true });
const lines = [
  `# Scenario library: validation and evaluation report`, "",
  `Generated by \`pnpm tsx scripts/ai-hr/evaluate.ts\` on ${new Date().toISOString().slice(0, 10)} from library version ${LIBRARY_VERSION}. Every number below comes from running each scenario through the conversation engine (rule-based, deterministic); nothing is estimated.`, "",
  `## Library`, "", `| | |`, `|---|---|`, `| Scenarios | ${v.total} |`, `| Categories | ${v.categories} |`, `| Structurally valid | ${v.valid} |`, `| Duplicate utterances | ${v.duplicates.length} |`, `| Problems | ${v.problems.length} |`, "",
  `## Result`, "", `| Split | Scenarios | Passed | Rate |`, `|---|---|---|---|`,
  ...Object.entries(r.bySplit).map(([k, x]) => `| ${k} | ${x.total} | ${x.passed} | ${pct(x.passed, x.total)} |`),
  `| **all** | ${r.total} | ${r.passed} | ${pct(r.passed, r.total)} |`, "",
  `A scenario passes only if **every** check passes. The held-out split (every fifth scenario) was written together with the others by the same author but was not used while tuning the rules; treat it as an indication, not an independent benchmark.`, "",
  `## Metrics (per check)`, "", `| Check | Checked | Passed | Rate |`, `|---|---|---|---|`,
  ...Object.entries(r.metrics).map(([k, m]) => `| ${k} | ${m.checked} | ${m.ok} | ${m.rate}% |`), "",
  `## Per category`, "", `| Category | Name | Scenarios | Passed |`, `|---|---|---|---|`,
  ...CATEGORIES.map((c) => `| ${c.id} | ${c.name} | ${r.byCategory[c.id]?.total ?? 0} | ${r.byCategory[c.id]?.passed ?? 0} |`), "",
  `## Failures (${r.failures.length})`, "",
  ...r.failures.map((f) => `- **${f.id}**: ${f.failed.join("; ")}`), "",
];
writeFileSync("docs/ai-hr-assistant/SCENARIO_REPORT.md", lines.join("\n"));
writeFileSync("docs/ai-hr-assistant/scenario-results.json", JSON.stringify({ version: LIBRARY_VERSION, validation: v, total: r.total, passed: r.passed, bySplit: r.bySplit, metrics: r.metrics, byCategory: r.byCategory, failures: r.failures.map((f) => ({ id: f.id, failed: f.failed })) }, null, 1) + "\n");
console.log(`scenarios ${v.total} in ${v.categories} categories, valid ${v.valid}, duplicates ${v.duplicates.length}, problems ${v.problems.length}`);
console.log(`passed ${r.passed}/${r.total}`, JSON.stringify(r.bySplit));
for (const [k, m] of Object.entries(r.metrics)) console.log(`  ${k}: ${m.ok}/${m.checked} (${m.rate}%)`);
if (!process.argv.includes("--quiet")) for (const f of r.failures) console.log(`FAIL ${f.id}: ${f.failed.join("; ")}\n    ${f.transcript.map((t) => `${t.who === "ai" ? "AI" : "E"}: ${t.text}`).join("\n    ")}`);
if (v.duplicates.length || v.problems.length) console.log("VALIDATION", v.duplicates, v.problems);
