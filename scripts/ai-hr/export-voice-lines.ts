// Exports what Naina actually says, for the voice tests and the Kokoro benchmark on the AI host:
//   hinglish  every Hinglish phrase variant in phrases.ts (placeholders left as {name}; tests strip them)
//   speech    the spoken text the app sends to /tts, from running all 1,000 scenarios through the engine (Devanagari
//             for Hindi/Hinglish conversations, English for English ones), de-duplicated
//   display   the matching on-screen replies (Roman Hinglish / Hindi / English)
// Run: pnpm tsx scripts/ai-hr/export-voice-lines.ts   (writes ai-service/tests/data/naina_lines.json)
import { mkdirSync, writeFileSync } from "node:fs";
import { start, step } from "../../src/staff/hrms/ai-hr/engine";
import { evalCtx } from "../../src/staff/hrms/ai-hr/evaluate";
import { P } from "../../src/staff/hrms/ai-hr/phrases";
import { LIBRARY_VERSION, scenarios } from "../../src/staff/hrms/ai-hr/scenarios";

const hinglish = new Set<string>();
for (const v of Object.values(P) as Record<string, string[]>[]) for (const s of v.hinglish ?? []) hinglish.add(s);

const speech = new Map<string, string>(); // speech -> display
let turns = 0;
for (const s of scenarios()) {
  const ctx = evalCtx(s.callReason);
  const first = start(s.callReason, ctx);
  if (first.speech) speech.set(first.speech, first.reply);
  let st = first.state;
  for (const u of s.turns) {
    if (st.ended) break;
    const r = step(st, ctx, u);
    st = r.state;
    turns++;
    if (r.reply && r.speech) speech.set(r.speech, r.reply);
  }
}
const out = {
  about: "Generated by scripts/ai-hr/export-voice-lines.ts from the app's phrase library and the scenario library; do not edit by hand.",
  library: LIBRARY_VERSION, turns,
  hinglish: [...hinglish].sort(),
  speech: [...speech.keys()].sort(),
  pairs: [...speech.entries()].sort((a, b) => a[0].localeCompare(b[0])).map(([s, d]) => ({ speech: s, display: d })),
};
mkdirSync("ai-service/tests/data", { recursive: true });
writeFileSync("ai-service/tests/data/naina_lines.json", JSON.stringify(out, null, 1) + "\n");
console.log(`hinglish variants ${out.hinglish.length}, distinct spoken lines ${out.speech.length} from ${turns} turns`);
